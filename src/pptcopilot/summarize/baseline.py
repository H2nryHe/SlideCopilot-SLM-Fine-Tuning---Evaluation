"""Baseline summarization with pluggable backends."""

from __future__ import annotations

import json
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Protocol

from pptcopilot.config import get_summarize_defaults


class Summarizer(Protocol):
    def summarize_document(self, slides: list[dict[str, object]]) -> str:
        ...


class MockSummarizer:
    """Deterministic summarizer for tests and local smoke runs."""

    def summarize_document(self, slides: list[dict[str, object]]) -> str:
        if not slides:
            return "No slide content available."
        focus_points: list[str] = []
        for slide in slides[:5]:
            text = str(slide.get("slide_text", "")).strip()
            if not text:
                continue
            sentence = text.split("|", 1)[0].strip()
            focus_points.append(sentence)
        if not focus_points:
            return "Slides were empty after ingestion."
        return (
            "Deck summary: "
            + "; ".join(focus_points)
            + ". This baseline summary is deterministic for regression checks."
        )


class HFSummarizer:
    """Optional local Hugging Face summarizer backend."""

    def __init__(self, model_name: str) -> None:
        try:
            from transformers import pipeline  # type: ignore
        except ImportError as exc:
            raise RuntimeError(
                "transformers is not installed. Use --model mock or install transformers."
            ) from exc
        self._pipeline = pipeline("text2text-generation", model=model_name, tokenizer=model_name)

    def summarize_document(self, slides: list[dict[str, object]]) -> str:
        if not slides:
            return "No slide content available."
        joined = " ".join(str(s.get("slide_text", "")) for s in slides).strip()
        if not joined:
            return "Slides were empty after ingestion."
        prompt = f"Summarize this presentation in 4 concise bullets: {joined}"
        result = self._pipeline(
            prompt,
            max_new_tokens=128,
            do_sample=False,
            temperature=0.0,
        )
        return str(result[0]["generated_text"]).strip()


class FineTunedMockSummarizer:
    """Adapter-backed deterministic summarizer for local finetune smoke runs."""

    def __init__(self, adapter_dir: str | Path) -> None:
        self.adapter_dir = Path(adapter_dir)
        cfg_path = self.adapter_dir / "adapter_config.json"
        if not cfg_path.exists():
            raise RuntimeError(f"Missing adapter config: {cfg_path}")
        self.adapter_cfg = json.loads(cfg_path.read_text(encoding="utf-8"))

    def summarize_document(self, slides: list[dict[str, object]]) -> str:
        if not slides:
            return "No slide content available."
        include_all_titles = bool(
            self.adapter_cfg.get("summary_behavior", {}).get("include_all_titles", True)
        )
        max_titles = int(self.adapter_cfg.get("summary_behavior", {}).get("max_titles", 6))

        titles: list[str] = []
        for slide in slides:
            text = str(slide.get("slide_text", "")).strip()
            if not text:
                continue
            titles.append(text.split("|", 1)[0].strip())
        if not titles:
            return "Slides were empty after ingestion."
        selected = titles if include_all_titles else titles[:max_titles]
        return (
            "Deck summary: "
            + "; ".join(selected[:max_titles])
            + ". Generated by finetuned adapter for style-consistent coverage."
        )


def _load_slides(jsonl_path: str | Path) -> list[dict[str, object]]:
    path = Path(jsonl_path)
    records: list[dict[str, object]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        records.append(json.loads(line))
    return records


def _build_slide_bullets(slides: list[dict[str, object]]) -> list[dict[str, str]]:
    bullets: list[dict[str, str]] = []
    for slide in slides:
        slide_id = str(slide.get("slide_id", ""))
        text = str(slide.get("slide_text", "")).strip()
        if not text:
            bullet = "(empty slide)"
        else:
            bullet = text.split("|", 1)[0].strip()
        bullets.append({"slide_id": slide_id, "bullet": bullet})
    return bullets


def _make_summarizer(model: str) -> Summarizer:
    defaults = get_summarize_defaults()
    if model == "mock":
        return MockSummarizer()
    if model.startswith("hf:"):
        return HFSummarizer(model_name=model.split(":", 1)[1])
    if model.startswith("finetuned:"):
        return FineTunedMockSummarizer(adapter_dir=model.split(":", 1)[1])
    raise ValueError(
        f"Unsupported model '{model}'. Use '{defaults.model}', 'hf:<model_name>', "
        "or 'finetuned:<adapter_dir>'."
    )


def summarize_jsonl(
    input_path: str | Path,
    *,
    model: str = "mock",
    include_slide_bullets: bool = True,
) -> dict[str, object]:
    defaults = get_summarize_defaults()
    slides = _load_slides(input_path)
    summarizer = _make_summarizer(model)

    start = time.perf_counter()
    document_summary = summarizer.summarize_document(slides)
    runtime_sec = time.perf_counter() - start

    output: dict[str, object] = {
        "metadata": {
            "model": model,
            "seed": defaults.seed,
            "temperature": defaults.temperature,
            "runtime_sec": round(runtime_sec, 6),
            "input_path": str(Path(input_path).resolve()),
            "n_slides": len(slides),
            "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        },
        "document_summary": document_summary,
    }
    if include_slide_bullets:
        output["slide_bullets"] = _build_slide_bullets(slides)
    return output


def write_summary(result: dict[str, object], output_path: str | Path) -> Path:
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(result, indent=2, ensure_ascii=True) + "\n", encoding="utf-8")
    return path
